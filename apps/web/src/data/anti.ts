import type { OpeningLine, OpponentMove, UserMove } from '../types';

function user(
  san: string,
  say: string,
  hint: string,
  why: string,
  plan?: string,
): UserMove {
  return {
    san,
    by: 'user',
    say,
    hint,
    why,
    ...(plan ? { plan } : {}),
  };
}

function opponent(san: string, say: string): OpponentMove {
  return { san, by: 'opponent', say };
}

