import type { Opening, OpeningLine, OpponentMove, UserMove } from '../types';

function user(
  san: string,
  say: string,
  hint: string,
  why: string,
  plan?: string,
  alternatives?: UserMove['alternatives'],
): UserMove {
  return {
    san,
    by: 'user',
    say,
    hint,
    why,
    ...(plan ? { plan } : {}),
    ...(alternatives ? { alternatives } : {}),
  };
}

function opponent(san: string, say: string): OpponentMove {
  return { san, by: 'opponent', say };
}

